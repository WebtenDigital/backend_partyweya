-- The area vocabulary and the zone each area places a venue in: the map the
-- register import used, never in the database until now. Seeded from
-- data/partyweya_area_zone_map.csv (187 areas, 24 zones). Its division column
-- is not stored: it matches Zone.division on every row.

CREATE TABLE "AreaZone" (
    "area" TEXT NOT NULL,
    "zoneName" TEXT NOT NULL,

    CONSTRAINT "AreaZone_pkey" PRIMARY KEY ("area")
);

CREATE INDEX "AreaZone_zoneName_idx" ON "AreaZone"("zoneName");

ALTER TABLE "AreaZone" ADD CONSTRAINT "AreaZone_zoneName_fkey" FOREIGN KEY ("zoneName") REFERENCES "Zone"("name") ON DELETE RESTRICT ON UPDATE CASCADE;

-- Internal like the rest of the register: RLS on, no grants.
ALTER TABLE "AreaZone" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON "AreaZone" FROM anon, authenticated;

